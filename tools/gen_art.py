#!/usr/bin/env python3
"""Generates pong/art.lua: pixel-art versions of the Solana mark for the badge.

The badge draws images from "rows" of characters (one character per pixel).
We rasterise the three bars of the Solana logo here, once, so the badge
doesn't spend its per-callback instruction budget doing it at launch.

Run:  python3 tools/gen_art.py
"""
import math
import os

# The Solana mark, in the official SVG's coordinates (397.7 x 311.7),
# corners left square. Each bar is a parallelogram (4 points, clockwise).
LOGO_W, LOGO_H = 397.7, 311.7
TOP = [(64.6, 0.0), (397.7, 0.0), (333.1, 77.7), (0.0, 77.7)]
MID = [(0.0, 116.3), (333.1, 116.3), (397.7, 194.0), (64.6, 194.0)]
BOT = [(64.6, 234.0), (397.7, 234.0), (333.1, 311.7), (0.0, 311.7)]
BARS = [TOP, MID, BOT]

# Solana gradient, purple (bottom-left) -> green (top-right), as palette chars.
GRADIENT = [
    ("A", 0x9945FF),
    ("B", 0x8752F3),
    ("C", 0x5497D5),
    ("D", 0x43B4CA),
    ("E", 0x28E0B9),
    ("F", 0x19FB9B),
]


def inside(poly, x, y):
    """Point in convex polygon (clockwise in y-down coordinates)."""
    n = len(poly)
    for i in range(n):
        x1, y1 = poly[i]
        x2, y2 = poly[(i + 1) % n]
        if (x2 - x1) * (y - y1) - (y2 - y1) * (x - x1) < 0:
            return False
    return True


def grad_char(lx, ly):
    # Project onto the diagonal from bottom-left (0, H) to top-right (W, 0).
    dx, dy = LOGO_W, -LOGO_H
    t = (lx * dx + (ly - LOGO_H) * dy) / (dx * dx + dy * dy)
    t = min(max(t, 0.0), 0.999)
    return GRADIENT[int(t * len(GRADIENT))][0]


def raster(w, h, to_logo, polys, ss=4, threshold=0.45):
    """Rasterise polygons into w x h rows. to_logo maps pixel space -> logo space."""
    rows = []
    for py in range(h):
        row = []
        for px in range(w):
            hits = 0
            for sy in range(ss):
                for sx in range(ss):
                    lx, ly = to_logo(px + (sx + 0.5) / ss, py + (sy + 0.5) / ss)
                    if any(inside(p, lx, ly) for p in polys):
                        hits += 1
            if hits / (ss * ss) >= threshold:
                lx, ly = to_logo(px + 0.5, py + 0.5)
                row.append(grad_char(lx, ly))
            else:
                row.append(".")
        rows.append("".join(row).rstrip(".") or ".")
    return rows


def logo(w, h, squash=1.0):
    """Whole mark in a w x h box; squash in [-1, 1] narrows/mirrors it (coin spin)."""
    def to_logo(px, py):
        cx = (px - w / 2) / (w / 2)          # -1..1 across the box
        cx = cx / squash                      # undo the squash
        return (cx + 1) / 2 * LOGO_W, py / h * LOGO_H
    return raster(w, h, to_logo, BARS)


def bar_vertical(bar, w, h):
    """One bar turned 90 degrees clockwise: its length runs down the screen."""
    xs = [p[0] for p in bar]
    ys = [p[1] for p in bar]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)

    def to_logo(px, py):
        lx = x0 + py / h * (x1 - x0)
        ly = y1 - px / w * (y1 - y0)
        return lx, ly
    return raster(w, h, to_logo, [bar])


def net(w, h, step):
    """A column of tiny middle bars (the S's middle stroke) for the centre line."""
    small = raster(w, 3, lambda px, py: (px / w * LOGO_W, 116.3 + py / 3 * 77.7), [MID], ss=4, threshold=0.4)
    rows = []
    y = 0
    while y < h:
        for r in small:
            if len(rows) < h:
                rows.append(r)
        while len(rows) < min(h, y + step):
            rows.append(".")
        y += step
    return rows


def lua_rows(rows, indent="    "):
    return "{\n" + "".join(f'{indent}  "{r}",\n' for r in rows) + indent + "}"


def main():
    out = []
    out.append("-- Generated by tools/gen_art.py. Do not edit by hand.\n")
    out.append("local art = {}\n\n")
    out.append("art.palette = {\n")
    for ch, col in GRADIENT:
        out.append(f"  {ch} = 0x{col:06X},\n")
    out.append("}\n\n")

    # Ball: the whole mark, 20 x 16, in 8 frames of a coin-flip spin.
    out.append("art.BALL_W, art.BALL_H = 20, 16\n")
    out.append("art.ball = {\n")
    for k in range(8):
        f = math.cos(math.radians(k * 45))
        if abs(f) < 0.2:
            f = 0.2 if f >= 0 else -0.2
        if k == 2:
            f = 0.2
        if k == 6:
            f = -0.2
        out.append("  " + lua_rows(logo(20, 16, f), "  ") + ",\n")
    out.append("}\n\n")

    # Paddles: left = bottom bar, right = top bar, each turned upright.
    out.append("art.PADDLE_W, art.PADDLE_H = 9, 44\n")
    out.append("art.paddle_left = " + lua_rows(bar_vertical(BOT, 9, 44), "") + "\n")
    out.append("art.paddle_right = " + lua_rows(bar_vertical(TOP, 9, 44), "") + "\n\n")

    # Centre net: middle bars.
    out.append("art.NET_W = 8\n")
    out.append("art.net = " + lua_rows(net(8, 196, 12), "") + "\n\n")

    # Title logo.
    out.append("art.LOGO_W, art.LOGO_H = 52, 41\n")
    out.append("art.logo = " + lua_rows(logo(52, 41), "") + "\n\n")
    out.append("return art\n")

    path = os.path.join(os.path.dirname(__file__), "..", "pong", "art.lua")
    with open(path, "w") as fh:
        fh.write("".join(out))
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
